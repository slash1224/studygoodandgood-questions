        /// <summary>随机取一条名言。若数据目录存在 quotes.txt（每行一条），优先使用自定义列表。</summary>
        public static string Pick()
        {
            try
            {
                var path = System.IO.Path.Combine(Guardian.DataDir, "quotes.txt");
                if (System.IO.File.Exists(path))
                {
                    var lines = System.IO.File.ReadAllLines(path);
                    var valid = Array.FindAll(lines, l => !string.IsNullOrWhiteSpace(l));
                    if (valid.Length > 0)
                        return valid[_rnd.Next(valid.Length)].Trim();
                }
            }
            catch { }
            return Builtin[_rnd.Next(Builtin.Length)];
        }
